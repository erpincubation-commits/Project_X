import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { randomUUID } from 'node:crypto';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { _electron } from 'playwright-core';

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL('../', import.meta.url));
require('../apps/server/dist/config.js');
const { Pool } = require('pg');
const { migrate } = require('../apps/server/dist/database/migrate.js');
const { totp } = require('../apps/server/dist/auth/crypto.js');
process.env.MFA_ENCRYPTION_KEY = '4'.repeat(64);
process.env.ADMIN_SETUP_TOKEN = '5'.repeat(64);
const originalUrl = process.env.DATABASE_URL;
assert.ok(originalUrl, 'Run npm run setup before the desktop smoke test.');
const schema = `erp_test_${randomUUID().replaceAll('-', '')}`;
assert.match(schema, /^erp_test_[a-f0-9]{32}$/);
const owner = new Pool({ connectionString: originalUrl });
const url = new URL(originalUrl);
url.searchParams.set('options', `-c search_path=${schema}`);
await owner.query(`CREATE SCHEMA "${schema}"`);
process.env.DATABASE_URL = url.toString();
const pool = new Pool({ connectionString: url.toString() });
const applications = [];
let server;
try {
  await migrate(pool);
  server = await require('../apps/server/dist/bootstrap.js').createApplication();
  await server.listen(0, '127.0.0.1');
  const serverUrl = await server.getUrl();
  const profileRoot = resolve(root, '.local', schema);
  await mkdir(profileRoot, { recursive: true });
  async function client(role) {
    const profile = resolve(profileRoot, role);
    await mkdir(profile, { recursive: true });
    const env = { ...process.env, ERP_SMOKE_PROFILE: profile };
    delete env.ELECTRON_RUN_AS_NODE;
    const application = await _electron.launch({ executablePath: require('electron'), args: [resolve(root, 'apps/desktop')], env, timeout: 30000 });
    applications.push(application);
    const page = await application.firstWindow();
    page.on('pageerror', error => console.error('Renderer error:', error.message));
    await page.getByLabel('Server address').fill(serverUrl);
    await page.getByRole('button', { name: 'Connect', exact: true }).click();
    await page.getByText(role === 'admin' ? 'Server connected. Create the initial administrator account.' : 'Server connected. You can sign in.', { exact: true }).waitFor();
    await page.getByLabel('Email', { exact: true }).fill(`${role}@smoke.test`);
    await page.getByLabel('Password', { exact: true }).fill('desktop-test-password');
    if (role === 'admin') {
      await page.getByLabel('Administrator setup code', { exact: true }).fill(process.env.ADMIN_SETUP_TOKEN);
      await page.getByLabel('Confirm password', { exact: true }).fill('desktop-test-password');
    }
    await page.getByRole('button', { name: role === 'admin' ? 'Create administrator' : 'Sign in', exact: true }).click();
    await page.getByRole('heading', { name: 'Set up your authenticator' }).waitFor();
    const secret = await page.locator('.secret-key').innerText();
    await page.getByLabel('Verification code', { exact: true }).fill(totp(secret));
    await page.getByRole('button', { name: 'Verify code', exact: true }).click();
    await page.getByRole('heading', { name: 'Save your recovery codes' }).waitFor();
    await page.getByRole('button', { name: 'I have saved my recovery codes', exact: true }).click();
    await page.getByRole('heading', { name: role==='business_approver'?'Purchasing workspace':'Your customers' }).waitFor();
    assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
    assert.deepEqual(await page.evaluate(() => Object.keys(window.erp).sort()), ['connect','createCustomer','getServer','listCustomers','login','logout','openLogs','reportError','setupStatus','setup','verifyMfa','me','revokeSessions','listUsers','createUser','updateUser','listAudit','listSuppliers','createSupplier','updateSupplier','listItems','createItem','updateItem','listPurchaseRequests','getPurchaseRequest','createPurchaseRequest','updatePurchaseRequest','submitPurchaseRequest','decidePurchaseRequest','listApprovers','recordHistory'].sort());
    return page;
  }
  const admin = await client('admin');
  await admin.getByRole('button', { name: 'Account security and access', exact: true }).click();
  await admin.getByLabel('New user email', { exact: true }).fill('reader@smoke.test');
  await admin.getByLabel('Initial password', { exact: true }).fill('desktop-test-password');
  await admin.getByRole('button', { name: 'Create account', exact: true }).click();
  await admin.getByRole('cell', { name: 'reader@smoke.test', exact: true }).waitFor();
  await admin.getByRole('button', { name: 'Refresh audit history', exact: true }).click();
  await admin.getByRole('cell', { name: 'user.created', exact: true }).waitFor();
  await admin.getByLabel('New user email', { exact: true }).fill('business_approver@smoke.test');
  await admin.getByLabel('Initial password', { exact: true }).fill('desktop-test-password');
  await admin.getByLabel('Role', {exact:true}).selectOption('business_approver');
  await admin.getByRole('button', { name: 'Create account', exact: true }).click();
  await admin.getByRole('cell', { name: 'business_approver@smoke.test', exact: true }).waitFor();
  await admin.getByRole('button', { name: 'Back to workspace', exact: true }).click();
  const reader = await client('reader');
  assert.equal(await reader.getByRole('button', { name: 'Save customer' }).count(), 0);
  await admin.getByLabel('Customer code', { exact: true }).fill('SMOKE-001');
  await admin.getByLabel('Customer name', { exact: true }).fill('Desktop integration customer');
  await admin.getByRole('button', { name: 'Save customer' }).click();
  await admin.getByText('Customer SMOKE-001 saved to the shared database.', { exact: true }).waitFor();
  await reader.getByRole('button', { name: 'Refresh customers' }).click();
  await reader.getByRole('cell', { name: 'Desktop integration customer', exact: true }).waitFor();
  const adminWindow = await applications[0].browserWindow(admin);
  await adminWindow.evaluate(window => window.showInactive());
  await admin.screenshot({ path: resolve(root, '.local/desktop-workflow.png') });
  assert.equal(await reader.getByRole('button',{name:'Purchasing',exact:true}).count(),0);
  await admin.getByRole('button',{name:'Purchasing',exact:true}).click();
  await admin.getByRole('button',{name:'Suppliers',exact:true}).click();
  await admin.getByLabel('Supplier code',{exact:true}).fill('SUP-SMOKE');
  await admin.getByLabel('Supplier name',{exact:true}).fill('Workshop supplier');
  await admin.getByRole('button',{name:'Save supplier',exact:true}).click();
  await admin.getByRole('cell',{name:'SUP-SMOKE',exact:true}).waitFor();
  await admin.getByRole('button',{name:'Items',exact:true}).click();
  await admin.getByLabel('Item code',{exact:true}).fill('ITEM-SMOKE');
  await admin.getByLabel('Item name',{exact:true}).fill('Workshop item');
  await admin.getByRole('button',{name:'Save item',exact:true}).click();
  await admin.getByRole('cell',{name:'ITEM-SMOKE',exact:true}).waitFor();
  await admin.getByRole('button',{name:'Purchase requests',exact:true}).click();
  await admin.getByRole('button',{name:'New purchase request',exact:true}).click();
  await admin.getByLabel('Request title',{exact:true}).fill('Workshop request');
  await admin.getByLabel('Currency',{exact:true}).fill('EUR');
  await admin.getByLabel('Justification',{exact:true}).fill('Supplies for the workshop');
  await admin.getByLabel('Preferred supplier (optional)',{exact:true}).selectOption({label:'SUP-SMOKE · Workshop supplier'});
  await admin.getByLabel('Item 1',{exact:true}).selectOption({label:'ITEM-SMOKE · Workshop item (EA)'});
  await admin.getByLabel('Quantity 1',{exact:true}).fill('2.5');
  await admin.getByLabel('Unit price 1',{exact:true}).fill('12.25');
  await admin.getByRole('button',{name:'Save draft',exact:true}).click();
  await admin.getByText('Status: DRAFT',{exact:true}).waitFor();
  await admin.getByLabel('Independent approver',{exact:true}).selectOption({label:'business_approver@smoke.test'});
  await admin.getByRole('button',{name:'Submit for approval',exact:true}).click();
  await admin.getByText('Status: SUBMITTED',{exact:true}).waitFor();
  assert.equal(await admin.getByRole('button',{name:'Approve request',exact:true}).count(),0);
  const approver=await client('business_approver');
  await approver.getByRole('button',{name:'Open PR-1',exact:true}).click();
  await approver.getByLabel('Decision reason',{exact:true}).fill('Choose a lower cost option');
  await approver.getByRole('button',{name:'Reject request',exact:true}).click();
  await approver.getByText('Status: REJECTED',{exact:true}).waitFor();
  await admin.getByRole('button',{name:'Refresh selected request',exact:true}).click();
  await admin.getByText('Status: REJECTED',{exact:true}).waitFor();
  await admin.getByRole('button',{name:'Revise request',exact:true}).click();
  await admin.getByLabel('Quantity 1',{exact:true}).fill('1.5');
  await admin.getByRole('button',{name:'Save draft',exact:true}).click();
  await admin.getByText('Status: DRAFT',{exact:true}).waitFor();
  await admin.getByLabel('Independent approver',{exact:true}).selectOption({label:'business_approver@smoke.test'});
  await admin.getByRole('button',{name:'Submit for approval',exact:true}).click();
  await admin.getByText('Status: SUBMITTED',{exact:true}).waitFor();
  await approver.getByRole('button',{name:'Refresh selected request',exact:true}).click();
  await approver.getByText('Status: SUBMITTED',{exact:true}).waitFor();
  await approver.getByRole('button',{name:'Approve request',exact:true}).click();
  await approver.getByText('Status: APPROVED',{exact:true}).waitFor();
  await admin.getByRole('button',{name:'Refresh selected request',exact:true}).click();
  await admin.getByText('Status: APPROVED',{exact:true}).waitFor();
  await admin.screenshot({path:resolve(root,'.local/procurement-workflow.png')});
  assert.equal((await pool.query("SELECT count(*) FROM erp_record_history WHERE entity_type='purchase_request'")).rows[0].count,'6');
  await reader.getByRole('button', { name: 'Sign out', exact: true }).click();
  await reader.getByRole('heading', { name: 'Connect to your workspace' }).waitFor();
  assert.equal((await pool.query('SELECT count(*) FROM erp_customers')).rows[0].count, '1');
  console.log('PASS: MFA, shared customers, supplier/item masters and independent request rejection, revision, approval and history across three Electron clients.');
} finally {
  for (const application of applications) await application.close();
  if (server) await server.close();
  await pool.end();
  process.env.DATABASE_URL = originalUrl;
  await owner.query(`DROP SCHEMA "${schema}" CASCADE`);
  await owner.end();
}
